import { writeFile } from "node:fs/promises";

import { teams } from "../src/data.js";
import { matchResultsById } from "../src/matchResultsData.js";
import { buildPlayerWorldCupStatsData } from "../src/playerWorldCupStatsImport.js";

const FIFA_LIVE_URL = "https://api.fifa.com/api/v3/live/football";
const DEFAULT_OUTPUT = new URL("../src/playerWorldCupStatsData.js", import.meta.url);
const output = process.argv[2] ? new URL(process.argv[2], `file://${process.cwd()}/`) : DEFAULT_OUTPUT;

const matchIds = Object.keys(matchResultsById).sort(
  (a, b) => Number(matchResultsById[a].matchNumber ?? 0) - Number(matchResultsById[b].matchNumber ?? 0)
);
const liveMatches = [];

for (const matchId of matchIds) {
  liveMatches.push(await fetchLiveMatch(matchId));
}

const data = buildPlayerWorldCupStatsData({ teams, liveMatches });
const contents = `// Generated by scripts/build-player-worldcup-stats.mjs.
// Source: FIFA live football API.

export const playerWorldCupStatsSource = {
  name: "FIFA",
  sourceUrl: "${FIFA_LIVE_URL}",
  syncedAt: ${JSON.stringify(new Date().toISOString())},
  matches: ${liveMatches.length}
};

export const playerWorldCupStatsByFifaId = ${JSON.stringify(data.playerWorldCupStatsByFifaId, null, 2)};

export const goalLeaderboard = ${JSON.stringify(data.goalLeaderboard, null, 2)};

export const assistLeaderboard = ${JSON.stringify(data.assistLeaderboard, null, 2)};
`;

await writeFile(output, contents);
console.log(`Generated ${output.pathname}: ${liveMatches.length} matches, ${data.goalLeaderboard.length} scorers, ${data.assistLeaderboard.length} assistants`);

async function fetchLiveMatch(matchId) {
  const response = await fetch(`${FIFA_LIVE_URL}/${matchId}`, {
    signal: AbortSignal.timeout(30_000),
    headers: {
      accept: "application/json",
      "accept-language": "en,zh-CN;q=0.9,zh;q=0.8",
      "user-agent":
        "Mozilla/5.0 (Macintosh; Intel Mac OS X 14_0) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/147.0 Safari/537.36"
    }
  });

  if (!response.ok) {
    throw new Error(`Failed to fetch FIFA live match ${matchId}: ${response.status} ${response.statusText}`);
  }

  return response.json();
}
