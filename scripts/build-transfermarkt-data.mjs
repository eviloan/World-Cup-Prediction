import { createReadStream } from "node:fs";
import { writeFile } from "node:fs/promises";
import path from "node:path";
import readline from "node:readline";

import { teams } from "../src/data.js";
import { buildTransfermarktProfiles } from "../src/transfermarktImport.js";

const datasetDir =
  process.argv[2] ?? path.join("assets", "DataSet-TransferMarkets", "Football Data from Transfermarkt");
const outputFile = process.argv[3] ?? path.join("src", "transfermarktData.js");

const files = {
  players: path.join(datasetDir, "players.csv"),
  valuations: path.join(datasetDir, "player_valuations.csv")
};

const playerRows = await readCsvFile(files.players);
const preliminary = buildTransfermarktProfiles({ teams, playerRows });
const playerIds = new Set(
  Object.values(preliminary.playersByFifaId).map((profile) => String(profile.transfermarktId))
);

const valuationRows = [];
for await (const row of readCsvRows(files.valuations)) {
  if (playerIds.has(String(row.player_id ?? ""))) valuationRows.push(row);
}

const result = buildTransfermarktProfiles({ teams, playerRows, valuationRows });
await writeTransfermarktData(outputFile, result);

console.log(
  `Generated ${outputFile}: ${result.summary.matchedPlayers}/${result.summary.fifaPlayers} FIFA players matched.`
);

async function readCsvFile(filePath) {
  const rows = [];
  for await (const row of readCsvRows(filePath)) rows.push(row);
  return rows;
}

async function* readCsvRows(filePath) {
  const input = createReadStream(filePath);
  const lines = readline.createInterface({ input, crlfDelay: Infinity });
  let headers = null;

  for await (const line of lines) {
    if (!headers) {
      headers = parseCsvLine(line);
      continue;
    }
    if (!line) continue;

    const values = parseCsvLine(line);
    const row = {};
    headers.forEach((header, index) => {
      row[header] = values[index] ?? "";
    });
    yield row;
  }
}

function parseCsvLine(line) {
  const values = [];
  let value = "";
  let quoted = false;

  for (let index = 0; index < line.length; index += 1) {
    const char = line[index];
    const next = line[index + 1];

    if (char === '"' && quoted && next === '"') {
      value += '"';
      index += 1;
      continue;
    }

    if (char === '"') {
      quoted = !quoted;
      continue;
    }

    if (char === "," && !quoted) {
      values.push(value);
      value = "";
      continue;
    }

    value += char;
  }

  values.push(value);
  return values;
}

async function writeTransfermarktData(filePath, result) {
  const body = `// Generated by scripts/build-transfermarkt-data.mjs from local Transfermarkt CSV data.
// Source: assets/DataSet-TransferMarkets/Football Data from Transfermarkt
// Matched FIFA players: ${result.summary.matchedPlayers}/${result.summary.fifaPlayers}

export const transfermarktSource = {
  name: "Transfermarkt",
  sourceUrl: "https://www.transfermarkt.co.uk/"
};

export const transfermarktPlayersByFifaId = ${JSON.stringify(result.playersByFifaId, null, 2)};

export function enrichTeamsWithTransfermarkt(teams, playersByFifaId = transfermarktPlayersByFifaId) {
  return teams.map((team) => {
    let teamMarketValue = 0;
    const players = team.players.map((player) => {
      const profile = playersByFifaId[String(player.fifaId)] ?? {};
      const marketAmount = normalizeMarketAmount(profile.marketValue);
      if (marketAmount) teamMarketValue += marketAmount;

      return {
        ...player,
        club: profile.club ?? player.club ?? "",
        marketValue: profile.marketValue ?? player.marketValue ?? "",
        highestMarketValue: profile.highestMarketValue ?? player.highestMarketValue ?? "",
        stats: {
          appearances: profile.stats?.appearances ?? player.stats?.appearances ?? null,
          goals: profile.stats?.goals ?? player.stats?.goals ?? null,
          assists: profile.stats?.assists ?? player.stats?.assists ?? null,
          minutesPlayed: profile.stats?.minutesPlayed ?? player.stats?.minutesPlayed ?? null
        },
        transfermarktUrl: profile.transfermarktUrl ?? player.transfermarktUrl ?? ""
      };
    });

    return {
      ...team,
      marketValue: team.marketValue || (teamMarketValue ? { amount: teamMarketValue, currency: "EUR" } : ""),
      transfermarktSource,
      players
    };
  });
}

function normalizeMarketAmount(value) {
  if (!value) return 0;
  if (typeof value === "number") return value;
  if (typeof value === "object" && typeof value.amount === "number") return value.amount;
  if (typeof value !== "string") return 0;

  const compact = value.replace(/[€£,\\s]/g, "").toLowerCase();
  const amount = Number.parseFloat(compact);
  if (!Number.isFinite(amount)) return 0;
  if (compact.includes("bn")) return amount * 1_000_000_000;
  if (compact.includes("m")) return amount * 1_000_000;
  if (compact.includes("k")) return amount * 1_000;
  return amount;
}
`;

  await writeFile(filePath, body);
}
