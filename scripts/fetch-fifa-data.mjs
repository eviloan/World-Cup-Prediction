import { writeFile } from "node:fs/promises";

import {
  FIFA_2026_SEASON_ID,
  FIFA_COMPETITION_ID,
  transformFifaData
} from "../src/fifaDataTransform.js";

const FIFA_API_BASE = "https://api.fifa.com/api/v3";
const LANGUAGE = "en";

async function main() {
  const teamsPayload = await fetchJson(
    `/competitions/teams/${FIFA_2026_SEASON_ID}?language=${LANGUAGE}`
  );
  const teams = teamsPayload.Results ?? [];
  const squadsByTeamId = {};

  for (const team of teams) {
    squadsByTeamId[team.IdTeam] = await fetchJson(
      `/teams/${team.IdTeam}/squad?idCompetition=${FIFA_COMPETITION_ID}&idSeason=${FIFA_2026_SEASON_ID}&language=${LANGUAGE}`
    );
  }

  const matchesPayload = await fetchJson(
    `/calendar/matches?idCompetition=${FIFA_COMPETITION_ID}&idSeason=${FIFA_2026_SEASON_ID}&language=${LANGUAGE}&count=500`
  );
  const data = transformFifaData({ teamsPayload, squadsByTeamId, matchesPayload });
  const generatedAt = new Date().toISOString();
  const sourceUrl =
    "https://www.fifa.com/en/tournaments/mens/worldcup/canadamexicousa2026";
  const contents = `// Generated by scripts/fetch-fifa-data.mjs from FIFA API data.
// Source: ${sourceUrl}
// Generated at: ${generatedAt}

export const teams = ${JSON.stringify(data.teams, null, 2)};

export const matches = ${JSON.stringify(data.matches, null, 2)};

export const dataSource = {
  name: "FIFA API",
  sourceUrl: "${sourceUrl}",
  generatedAt: "${generatedAt}",
  idCompetition: "${FIFA_COMPETITION_ID}",
  idSeason: "${FIFA_2026_SEASON_ID}"
};

export function getMatchById(matchId) {
  return matches.find((match) => match.id === matchId);
}

export function serializeMatch(match) {
  const home = match.homeTeamId ? teams[match.homeTeamId] : null;
  const away = match.awayTeamId ? teams[match.awayTeamId] : null;

  return {
    ...match,
    homeTeam: home,
    awayTeam: away
  };
}
`;

  await writeFile("src/data.js", contents);

  const squadCount = Object.values(data.teams).reduce((sum, team) => sum + team.players.length, 0);
  console.log(
    `Fetched ${Object.keys(data.teams).length} teams, ${squadCount} players, ${data.matches.length} matches.`
  );
}

async function fetchJson(path) {
  const response = await fetch(`${FIFA_API_BASE}${path}`);
  if (!response.ok) {
    throw new Error(`FIFA API ${path} returned HTTP ${response.status}`);
  }
  return response.json();
}

await main();
