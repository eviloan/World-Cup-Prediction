import { createReadStream } from "node:fs";
import { writeFile } from "node:fs/promises";
import path from "node:path";
import readline from "node:readline";

import { matches, teams } from "../src/data.js";
import { buildTeamHistoryData } from "../src/teamHistoryImport.js";

const datasetDir =
  process.argv[2] ?? path.join("assets", "DataSet-TransferMarkets", "Football Data from Transfermarkt");
const outputFile = process.argv[3] ?? path.join("src", "teamHistoryData.js");
const gamesFile = path.join(datasetDir, "games.csv");

const gameRows = [];
for await (const row of readCsvRows(gamesFile)) {
  if (row.competition_type === "national_team_competition") gameRows.push(row);
}

const result = buildTeamHistoryData({
  teams,
  currentMatches: matches,
  gameRows
});

await writeTeamHistoryData(outputFile, result);

console.log(
  `Generated ${outputFile}: ${result.summary.teams} teams, ${result.summary.games} national-team games processed.`
);

async function* readCsvRows(filePath) {
  const input = createReadStream(filePath);
  const lines = readline.createInterface({ input, crlfDelay: Infinity });
  let headers = null;

  for await (const line of lines) {
    if (!headers) {
      headers = parseCsvLine(line);
      continue;
    }
    if (!line) continue;

    const values = parseCsvLine(line);
    const row = {};
    headers.forEach((header, index) => {
      row[header] = values[index] ?? "";
    });
    yield row;
  }
}

function parseCsvLine(line) {
  const values = [];
  let value = "";
  let quoted = false;

  for (let index = 0; index < line.length; index += 1) {
    const char = line[index];
    const next = line[index + 1];

    if (char === '"' && quoted && next === '"') {
      value += '"';
      index += 1;
      continue;
    }

    if (char === '"') {
      quoted = !quoted;
      continue;
    }

    if (char === "," && !quoted) {
      values.push(value);
      value = "";
      continue;
    }

    value += char;
  }

  values.push(value);
  return values;
}

async function writeTeamHistoryData(filePath, result) {
  const body = `// Generated by scripts/build-team-history-data.mjs from local Transfermarkt CSV data.
// Source: assets/DataSet-TransferMarkets/Football Data from Transfermarkt
// Teams: ${result.summary.teams}
// National-team games processed: ${result.summary.games}

export const teamHistorySource = {
  name: "Transfermarkt",
  sourceUrl: "https://www.transfermarkt.co.uk/"
};

export const teamHistoryByTeamId = ${JSON.stringify(result.teamHistoryByTeamId, null, 2)};
`;

  await writeFile(filePath, body);
}
