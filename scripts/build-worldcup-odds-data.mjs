async function fetchOddsPage(url) {
  const response = await fetch(url, {
    headers: {
      "accept": "text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8",
      "accept-language": "zh-CN,zh;q=0.9,en;q=0.8",
      "user-agent":
        "Mozilla/5.0 (iPhone; CPU iPhone OS 18_0 like Mac OS X) AppleWebKit/605.1.15 (KHTML, like Gecko) CriOS/147.0 Mobile/15E148 Safari/604.1"
    }
  });

  if (!response.ok) {
    throw new Error(`Failed to fetch odds page: ${response.status} ${response.statusText}`);
  }

  return response.text();
}

function parseOddsByMatchId(pageHtml) {
  const tableStart = pageHtml.indexOf('<table class="wc-match-odds-table"');
  if (tableStart < 0) throw new Error("Could not find wc-match-odds-table");

  const tableEnd = pageHtml.indexOf("</table>", tableStart);
  if (tableEnd < 0) throw new Error("Could not find wc-match-odds-table end");

  const tableHtml = pageHtml.slice(tableStart, tableEnd);
  const rowPattern =
    /<tr class="([^"]*)">([\s\S]*?)<\/tr>\s*<tr class="wc-match-secondary-row[^"]*">([\s\S]*?)<\/tr>/g;
  const matchIdByPair = buildMatchIdByPair();
  const result = {};
  const unmatched = [];

  let rowMatch;
  while ((rowMatch = rowPattern.exec(tableHtml))) {
    const [, , mainRow, secondaryRow] = rowMatch;
    const [homeNameZh, awayNameZh] = extractAll(mainRow, /<span class="wc-match-team-name">([^<]+)<\/span>/g);
    const [homeWin, draw, awayWin] = extractAll(
      mainRow,
      /<span class="wc-match-odds-value">\s*([^<]+?)\s*<\/span>/g
    );

    if (!homeNameZh || !awayNameZh || !homeWin || !draw || !awayWin) continue;

    const homeName = TEAM_NAME_ZH_TO_APP_NAME[homeNameZh] ?? homeNameZh;
    const awayName = TEAM_NAME_ZH_TO_APP_NAME[awayNameZh] ?? awayNameZh;
    const matchId = matchIdByPair.get(`${normalizeName(homeName)}__${normalizeName(awayName)}`);

    if (!matchId) {
      unmatched.push(`${homeNameZh} vs ${awayNameZh}`);
      continue;
    }

    result[matchId] = {
      source: "World Cup Odds",
      sourceUrl: WORLD_CUP_ODDS_URL,
      updatedText: extractUpdatedText(secondaryRow),
      homeWin,
      draw,
      awayWin
    };
  }

  if (unmatched.length > 0) {
    throw new Error(`Could not match odds rows: ${unmatched.join(", ")}`);
  }

  return result;
}

function parseChampionOdds(pageHtml) {
  const wrapperStart = pageHtml.indexOf('id="winner-odds"');
  if (wrapperStart < 0) return [];

  const tableStart = pageHtml.indexOf('<table class="wc-odds-table"', wrapperStart);
  const tableEnd = pageHtml.indexOf("</table>", tableStart);
  if (tableStart < 0 || tableEnd < 0) return [];

  const wrapperEnd = pageHtml.indexOf("</div>", tableEnd);
  const tableHtml = pageHtml.slice(tableStart, tableEnd);
  const updatedText = extractOddsUpdatedText(pageHtml.slice(tableEnd, wrapperEnd > tableEnd ? wrapperEnd : tableEnd + 1000));
  const teamByName = buildTeamByName();
  const result = [];

  for (const row of extractAll(tableHtml, /<tr[^>]*>([\s\S]*?)<\/tr>/g)) {
    const rank = Number(row.match(/<span class="wc-odds-rank">\s*(\d+)\s*<\/span>/)?.[1]);
    const teamNameZh = decodeHtml(row.match(/<span class="wc-odds-team-name">\s*([^<]+?)\s*<\/span>/)?.[1]?.trim() ?? "");
    const values = extractAll(row, /<span class="wc-odds-value[^"]*">\s*([^<]+?)\s*<\/span>/g);
    if (!rank || !teamNameZh || values.length === 0) continue;

    const appName = TEAM_NAME_ZH_TO_APP_NAME[teamNameZh] ?? teamNameZh;
    const team = teamByName.get(normalizeName(appName));
    result.push({
      rank,
      teamId: team?.id ?? "",
      teamName: team?.name ?? appName,
      teamNameZh,
      odds: values[0],
      secondaryOdds: values[1] ?? "",
      updatedText,
      source: "World Cup Odds",
      sourceUrl: WORLD_CUP_ODDS_URL
    });
  }

  return result.sort((a, b) => a.rank - b.rank);
}

function buildMatchIdByPair() {
  return new Map(
    matches
      .filter((match) => teams[match.homeTeamId] && teams[match.awayTeamId])
      .map((match) => [
        `${normalizeName(teams[match.homeTeamId].name)}__${normalizeName(teams[match.awayTeamId].name)}`,
        match.id
      ])
  );
}

function buildTeamByName() {
  return new Map(Object.values(teams).map((team) => [normalizeName(team.name), team]));
}

function extractAll(html, pattern) {
  return [...html.matchAll(pattern)].map((match) => decodeHtml(match[1].trim()));
}

function extractUpdatedText(html) {
  const updated = html.match(/更新于\s*([^<]+?)\s*<\/span>/)?.[1]?.trim();
  return updated ? `更新于 ${decodeHtml(updated)}` : "";
}

function extractOddsUpdatedText(html) {
  const updated = html.match(/赔率更新时间:\s*([^<]+?)\s*<\/p>/)?.[1]?.trim();
  return updated ? `赔率更新时间: ${decodeHtml(updated)}` : "";
}

function normalizeName(value) {
  return String(value)
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/ı/g, "i")
    .replace(/[^a-z0-9]+/gi, " ")
    .trim()
    .toLowerCase();
}

function decodeHtml(value) {
  return value
    .replace(/&amp;/g, "&")
    .replace(/&#039;/g, "'")
    .replace(/&quot;/g, '"')
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">");
}
