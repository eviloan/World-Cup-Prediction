import { writeFile } from "node:fs/promises";

import { teams, matches, dataSource } from "../src/data.js";
import { transfermarktPlayersByFifaId } from "../src/transfermarktData.js";
import { applyTeamRatings, extractRankingPubDate } from "../src/teamRatings.js";

const FIFA_RANKINGS_URL = "https://api.fifa.com/api/v3/rankings?gender=1&count=300&language=en";
const OUTPUT_FILE = new URL("../src/data.js", import.meta.url);

const rankingRows = await fetchFifaRankings();
const ratedTeams = applyTeamRatings(teams, rankingRows, transfermarktPlayersByFifaId);
const rankingPubDate = extractRankingPubDate(rankingRows);
const generatedAt = new Date().toISOString();

await writeFile(OUTPUT_FILE, renderDataModule({ ratedTeams, matches, dataSource, generatedAt, rankingPubDate }));

console.log(`Updated ${Object.keys(ratedTeams).length} teams from FIFA rankings (${rankingPubDate || "unknown date"}).`);

async function fetchFifaRankings() {
  const response = await fetch(FIFA_RANKINGS_URL, {
    headers: {
      accept: "application/json",
      "user-agent": "WorldCup AI Predictor data updater"
    }
  });

  if (!response.ok) {
    throw new Error(`FIFA rankings request failed: ${response.status} ${response.statusText}`);
  }

  const payload = await response.json();
  const rows = payload.Results ?? payload.results ?? [];
  if (!Array.isArray(rows) || rows.length === 0) {
    throw new Error("FIFA rankings response did not include ranking rows.");
  }

  return rows;
}

function renderDataModule({ ratedTeams, matches, dataSource, generatedAt, rankingPubDate }) {
  const nextDataSource = {
    ...dataSource,
    teamRatings: {
      name: "FIFA ranking + Transfermarkt positional market value estimates",
      fifaRankingUrl: FIFA_RANKINGS_URL,
      fifaRankingPubDate: rankingPubDate,
      generatedAt,
      model: "FIFA rank blended with log-scaled Transfermarkt player market values by position."
    }
  };

  return `// Generated by scripts/fetch-fifa-data.mjs from FIFA API data.
// Team ratings updated by scripts/update-team-ratings.mjs.
// Source: ${dataSource.sourceUrl}
// FIFA rankings: ${FIFA_RANKINGS_URL}
// Generated at: ${generatedAt}

export const teams = ${JSON.stringify(ratedTeams, null, 2)};

export const matches = ${JSON.stringify(matches, null, 2)};

export const dataSource = ${JSON.stringify(nextDataSource, null, 2)};

export function getMatchById(matchId) {
  return matches.find((match) => match.id === matchId);
}

export function serializeMatch(match) {
  const home = match.homeTeamId ? teams[match.homeTeamId] : null;
  const away = match.awayTeamId ? teams[match.awayTeamId] : null;

  return {
    ...match,
    homeTeam: home,
    awayTeam: away
  };
}
`;
}
