import { readFile, writeFile } from "node:fs/promises";

import { matches, teams } from "../src/data.js";
import { buildMatchResultsData } from "../src/matchResultsImport.js";

const FIFA_MATCHES_URL =
  "https://api.fifa.com/api/v3/calendar/matches?idCompetition=17&idSeason=285023&language=en&count=500";
const OUTPUT_FILE = new URL("../src/matchResultsData.js", import.meta.url);

const input = process.argv[2] ?? FIFA_MATCHES_URL;
const payload = input.startsWith("http") ? await fetchJson(input) : JSON.parse(await readFile(input, "utf8"));
const result = buildMatchResultsData({ teams, matchesPayload: payload });
const generatedAt = new Date().toISOString();
const finishedMatchIds = new Set(Object.keys(result.matchResultsById));

const contents = `// Generated by scripts/build-match-results-data.mjs from FIFA API data.
// Source: ${FIFA_MATCHES_URL}
// Generated at: ${generatedAt}

export const matchResultsSource = {
  name: "FIFA API",
  sourceUrl: "${FIFA_MATCHES_URL}",
  generatedAt: "${generatedAt}",
  finishedMatches: ${finishedMatchIds.size},
  scheduledMatches: ${matches.length}
};

export const matchResultsById = ${JSON.stringify(result.matchResultsById, null, 2)};

export const teamTournamentStatsById = ${JSON.stringify(result.teamTournamentStatsById, null, 2)};
`;

await writeFile(OUTPUT_FILE, contents);
console.log(`Generated ${OUTPUT_FILE.pathname}: ${finishedMatchIds.size} finished matches`);

async function fetchJson(url) {
  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(`FIFA API returned HTTP ${response.status}`);
  }
  return response.json();
}
